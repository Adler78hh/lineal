import { createHash } from 'node:crypto';
import { readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { type Plugin, defineConfig } from 'vite';

function filesIn(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? filesIn(path) : [path];
  });
}

/**
 * Writes sw.js with the list of every file of the build, so the whole app is stored for
 * offline use on the first visit. The cache name changes with the files, so a new version
 * replaces the old one.
 */
function serviceWorker(): Plugin {
  return {
    name: 'lineal-service-worker',
    apply: 'build',
    generateBundle(_, bundle) {
      const publicFiles = filesIn('public').map((f) => relative('public', f).split('\\').join('/'));
      const files = ['./', ...Object.keys(bundle), ...publicFiles].filter((f) => f !== 'sw.js');
      const version = createHash('sha1').update(files.join('\n')).digest('hex').slice(0, 10);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by vite.config.ts\nconst CACHE = 'lineal-${version}';\nconst FILES = ${JSON.stringify(files)};\n${SW_BODY}`,
      });
    },
  };
}

// Pages: network first (for updates), cached copy when offline. Everything else: cache first,
// the file names carry a hash and never change.
const SW_BODY = `
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)));
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('lineal-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          if (res.ok) caches.open(CACHE).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./')),
    );
    return;
  }
  event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`;

// Relative base so the build works on GitHub Pages in a sub-folder.
// Older iPads run Safari 14/15, so the code is translated down for them.
export default defineConfig({
  base: './',
  plugins: [serviceWorker()],
  build: {
    target: ['es2020', 'safari14', 'chrome87', 'firefox78', 'edge88'],
    cssTarget: ['safari14', 'chrome87', 'firefox78', 'edge88'],
  },
});
